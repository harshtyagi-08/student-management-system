require('dotenv').config();
const express=require('express');
const cors=require('cors');
const rateLimit=require('express-rate-limit');
const connectDB=require('./config/db');
const authRoutes=require('./routes/auth');
const studentRoutes=require('./routes/students');
const attendanceRoutes=require('./routes/attendance');
const app=express();
app.use(cors({origin:process.env.CLIENT_URL?.split(',')||'http://localhost:5173'}));
app.use(express.json({limit:'1mb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,max:300,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'CampusTrack API'}));
app.use('/api/auth',authRoutes);
app.use('/api/students',studentRoutes);
app.use('/api/attendance',attendanceRoutes);
app.use((err,req,res,next)=>{console.error(err);res.status(err.status||500).json({message:err.message||'Internal server error'});});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log('SAMS API listening on '+port))).catch(err=>{console.error('Database connection failed:',err.message);process.exit(1)});
